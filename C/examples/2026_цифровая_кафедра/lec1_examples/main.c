/*

Вычисляет индекс массы тела

ИМТ = масса (в кг) / рост^2 (в метрах)

*/



// Раздел подключения библиотек (модулей)
#include <stdio.h>
// вверху подключен модуль для ввода и вывода
#include <math.h>

// Главная программа (главная функция) - main
int main()
{


    // объявление переменных
    float mass = 0.0;               // масса тела человека, в кг.
    float height = 0.0;             // рост человека, в метрах
    float I = 0.0;                  // Индекс массы тела

    // считывание значений вводимых пользователем
    printf("масса (кг) = ");
    scanf("%f", &mass);

    printf("рост (м) = ");
    scanf("%f", &height);


    // вычисления
    I = mass / powf(height, 2.0);

    printf("ИМТ = %.1f", I);

    printf("\n");

    // 18.5 <= I <= 25.5
    if ( (I >= 18.5) && ( I <= 25.0 ) ){
        printf("ИМТ в норме");
    }
    else{
        printf("ИМТ НЕ в норме");
    }



}
